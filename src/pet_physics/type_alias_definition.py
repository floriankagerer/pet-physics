"""Contains custom type aliases used in the package."""

Position3d = tuple[float, float, float]
"""A type alias for a position in 3D space, represented as a tuple of three floats (x, y, z)."""
Size3d = tuple[float, float, float]
"""A type alias for a size in 3D space, represented as a tuple of three floats (length, width, height)."""
Vector3d = tuple[float, float, float]
"""A type alias for a 3D vector."""
Vector4d = tuple[float, float, float, float]
"""A type alias for a 4D vector."""
